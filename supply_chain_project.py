# Extract the features (X) and target (y)
X = df.loc[:, 'Production volumes'].values.reshape(-1, 1)
y = df.loc[:, 'Manufacturing costs'].values

# Define the number of folds for cross-validation
num_folds = 5

# Initialize lists to store evaluation metrics
mse_scores = []
rmse_scores = []
mae_scores = []
r2_scores = []

from sklearn.preprocessing import MinMaxScaler

# Initialize and fit the scaler to the data
scaler = MinMaxScaler()
scaler.fit(X)

# Create a KFold object
kf = KFold(n_splits=num_folds, shuffle=True, random_state=42)

import tensorflow as tf
from tensorflow.keras.layers import Dense, Input # Import Input layer
from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint

# Define Early Stopping callback (can be defined once outside the loop)
early_stopping = EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True)

# Define Model Checkpoint callback (can be defined once outside the loop)
# The filepath for ModelCheckpoint needs to be unique if you want to save each fold's best model,
# or overwritten if you only care about the very best across all folds. For simplicity here,
# it will overwrite each time, saving the best from the *last* fold's training.
model_checkpoint = ModelCheckpoint('/kaggle/working/best_model.weights.h5', save_best_only=True, save_weights_only=True, monitor='val_loss', mode='min')

for i, (train_index, test_index) in enumerate(kf.split(X)): # Added enumerate to potentially use fold_idx for unique filepaths
    X_train, X_test = X[train_index], X[test_index]
    y_train, y_test = y[train_index], y[test_index]

    # Scale the data
    X_train_scaled = scaler.transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # Define and compile the neural network model inside the loop for each fold
    # This ensures a fresh model is trained for each fold of cross-validation.
    model = tf.keras.Sequential([
        Input(shape=(1,)), # Correct way to define input shape
        Dense(64, activation='relu'),
        Dense(32, activation='relu'),
        Dense(1)
    ])

    model.compile(optimizer='adam', loss='mean_squared_error')

    # Train the model on the training data with callbacks
    history = model.fit(X_train_scaled,
                        y_train, epochs=100,
                        batch_size=32,
                        validation_data=(X_test_scaled, y_test),
                        callbacks=[early_stopping, model_checkpoint],
                        verbose=0) # Suppress verbose output to reduce log size

    # Load the best model weights from the saved checkpoint for evaluation
    model.load_weights('/kaggle/working/best_model.weights.h5')

    # Make predictions on the test set
    y_pred = model.predict(X_test_scaled).flatten() # Flatten y_pred to match y_test shape

    # Calculate metrics
    mse = mean_squared_error(y_test, y_pred)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)

    # Calculate metrics as percentages
    target_range = np.max(y_test) - np.min(y_test)
    percentage_mse = (mse / target_range) * 100
    percentage_rmse = (rmse / target_range) * 100
    percentage_mae = (mae / target_range) * 100
    percentage_r2 = (r2 * 100)

    # Append the scores to the respective lists
    mse_scores.append(percentage_mse)
    rmse_scores.append(percentage_rmse)
    mae_scores.append(percentage_mae)
    r2_scores.append(percentage_r2)

# Calculate the average scores over all folds
avg_mse = np.mean(mse_scores)
avg_rmse = np.mean(rmse_scores)
avg_mae = np.mean(mae_scores)
avg_r2 = np.mean(r2_scores)


"""* EOQ (Economic Order Quality )
* EOQ tells how much quantity we should order at one time so that our ordering cost is low , holding cost is low and we nevwe run out of stock
"""

holdingcost=0.2

def calculate_eoq(data):

  S=data['Costs']
  D=data['Number of products sold']
  H=data['Number of products sold'] * holdingcost
  EOQ=np.sqrt((2*D*S)/H)
  return round(EOQ,2)

df['EOQ']=calculate_eoq(df)
